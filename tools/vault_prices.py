#!/usr/bin/env python3
"""Rebuilds js/74-vault-prices.js: one fixed price for every Knowledge Vault lesson / fact / word.

The price of an entry = about how many watts a player is holding when the thing it talks about unlocks.
We find that out by letting the game's own test-mode bot (AUTOPLAY at MAX, a fresh save) play the real
economy, and noting, the first time each entry becomes visible, the most watts held in the 10 game
minutes before. Entries that unlock at the same moment are spread from 1% to 100% of that amount in
their tab order, so the page still climbs; an entry that unlocks alone costs 10%.

Run from the repo root after any economy change (needs Playwright + Chrome):
    python3 -m http.server 8765 &      python3 tools/vault_prices.py
"""
import asyncio, json, math, os, sys
from playwright.async_api import async_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHROME = os.environ.get('CHROME', '/usr/bin/google-chrome')
URL = os.environ.get('GAME_URL', 'http://localhost:8765/index.html?test')
FLOOR, EARLY_TOP = 50, 500          # the very first entries: 50 W up to 500 W
MANUAL = {'b_party': 1e6}           # things the bot never does (it doesn't buy an Alien Party): priced by hand
HOOK = """(()=>{ window.__rec={}; window.__hist=[]; let lastT=0;
 window.__tmHook=(t)=>{ const h=window.__hist; h.push([t,score]); while(h.length&&h[0][0]<t-600)h.shift();
   if(t-lastT<20)return; lastT=t; let m=0; for(let i=0;i<h.length;i++)if(h[i][1]>m)m=h[i][1];
   VAULT_TABS.forEach(tab=>{ if(!vaultTabOpen(tab.id))return; vaultEntries(tab.id).forEach(e=>{ if(window.__rec[e.id]||!e.on())return; window.__rec[e.id]={t:Math.round(t),peak:m}; }); });
   window.__t=t; }; return 1;})()"""
IDS = "(()=>{const o=[];VAULT_TABS.forEach(t=>vaultEntries(t.id).forEach((e,i)=>o.push([e.id,t.id,i])));return o;})()"

def nice(n):
    if n < 100: return int(round(n))
    p = 10 ** (math.floor(math.log10(n)) - 1)
    return round(n / p) * p

def prices(rec, ids):
    order = {i[0]: k for k, i in enumerate(ids)}
    groups = {}
    for i in ids:
        if i[0] in rec: groups.setdefault(rec[i[0]]['t'], []).append(i[0])
    out = {}
    for t, g in groups.items():
        g.sort(key=lambda x: order[x]); peak = max(rec[x]['peak'] for x in g); n = len(g)
        for k, x in enumerate(g):
            if peak < 5000: lo, hi = FLOOR, max(EARLY_TOP, peak)
            else: lo, hi = peak * .01, peak
            v = (lo * hi) ** .5 * .32 if n == 1 and peak >= 5000 else lo * (hi / lo) ** (k / max(1, n - 1))
            out[x] = max(FLOOR, nice(v))
    out.update(MANUAL)
    return out

async def play():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=CHROME, args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width': 1280, 'height': 720})
        await pg.add_init_script("window.__noIntro=true;try{localStorage.clear()}catch(e){}")
        await pg.goto(URL); await pg.wait_for_timeout(1500)
        await pg.evaluate("startGame(0)"); await pg.wait_for_timeout(1500)
        for _ in range(6):
            await pg.mouse.click(1270, 710); await pg.wait_for_timeout(300)
        await pg.wait_for_timeout(2500)
        await pg.evaluate(HOOK)
        await pg.evaluate("TM.opts.speed='max';TM.opts.stopHours='';TM.opts.stallHours=12;TM.startAutoplay();1")
        last = None
        for k in range(120):
            await pg.wait_for_timeout(5000)
            st = await pg.evaluate("[Math.round(window.__t||0),Object.keys(window.__rec).length]")
            print('game hours %.1f, entries unlocked %d' % (st[0] / 3600, st[1]), flush=True)
            if st == last and k > 4: break
            last = st
        rec = await pg.evaluate("window.__rec"); ids = await pg.evaluate(IDS); ver = await pg.evaluate("GAME_VERSION")
        await b.close(); return rec, ids, ver

def main():
    cache = sys.argv[1] if len(sys.argv) > 1 else None   # optional: reuse a saved run (json with rec + ids)
    if cache and os.path.exists(cache): d = json.load(open(cache)); rec, ids, ver = d['rec'], d['ids'], d['ver']
    else:
        rec, ids, ver = asyncio.run(play())
        if cache: json.dump({'rec': rec, 'ids': ids, 'ver': ver}, open(cache, 'w'))
    pr = prices(rec, ids)
    miss = [i[0] for i in ids if i[0] not in pr]
    lines = ["// GENERATED by tools/vault_prices.py from a test-mode bot run of v%s. Don't edit by hand: rerun the tool after economy changes." % ver,
             "// Each Knowledge Vault entry's fixed price = about the watts a player holds when its feature unlocks (see the tool's header).",
             "// An entry that isn't listed (new content since the last run) costs the same as the entry before it in its tab (js/68 vaultEntryCost).",
             "const VAULT_PRICE={"]
    tab = None
    for i in ids:
        if i[0] not in pr: continue
        if i[1] != tab: tab = i[1]; lines.append("  // " + tab)
        v = pr[i[0]]; lines.append("  %s:%s," % (json.dumps(i[0]), ('%d' % v) if v < 1e15 else ('%.1e' % v).replace('e+', 'e')))
    lines.append("};")
    open(os.path.join(ROOT, 'js', '74-vault-prices.js'), 'w').write("\n".join(lines) + "\n")
    print('wrote %d prices; not reached by the bot (inherit the previous price): %s' % (len(pr), miss))
main()
